-- Devuelve TRUE si el usuario autenticado es superadmin.
create or replace function public.es_superadmin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.perfiles p
    where p.id = auth.uid() and p.rol = 'superadmin'
  );
$$;

-- Devuelve el id de la barberia a la que pertenece el usuario autenticado.

create or replace function public.barberia_del_usuario()
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select p.barberia_id
    from public.perfiles p
   where p.id = auth.uid()
     and p.rol = 'admin'
     and p.barberia_id is not null
   limit 1;
$$;

-- Devuelve TRUE si el usuario autenticado es superadmin o admin.
create or replace function public.es_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.perfiles p
    where p.id = auth.uid() and p.rol in ('superadmin', 'admin')
  );
$$;

-- Devuelve el rol del usuario autenticado (NULL si no hay sesion).
create or replace function public.rol_actual()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select p.rol from public.perfiles p where p.id = auth.uid();
