create or replace function public.unirme_a_barberia(p_barberia_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_rol text;
begin
  if auth.uid() is null then
    raise exception 'sin_sesion';
  end if;

  select p.rol into v_rol from public.perfiles p where p.id = auth.uid();
  if coalesce(v_rol, 'cliente') <> 'cliente' then
    raise exception 'solo_clientes';
  end if;

  if not exists (select 1 from public.barberias b where b.id = p_barberia_id and b.activa) then
    raise exception 'barberia_no_disponible';
  end if;

  insert into public.membresias (user_id, barberia_id)
  values (auth.uid(), p_barberia_id)
  on conflict (user_id, barberia_id) do nothing;
end;
$$;

-- 8.2 cancelar_cita: cancela liberando la franja -----------------------------
-- security definer porque el cliente solo tiene SELECT sobre `citas`;
-- por eso el cambio de estado tiene que pasar por aqui.
create or replace function public.cancelar_cita(p_id uuid)
returns void
language plpgsql
security definer
set search_path = 'public'
as $$
begin
  update public.citas
     set estado = 'cancelada'
   where id = p_id
     and cliente_id = auth.uid()
     and estado in ('pendiente', 'confirmada')
     and (fecha + hora) > (now() at time zone 'America/Mexico_City');

  if not found then
    raise exception 'cita_no_modificable';
  end if;
end;
$$;

-- 8.3 reagendar_cita: mueve la cita a otra franja libre ----------------------
create or replace function public.reagendar_cita(
  p_id   uuid,
  p_fecha date,
  p_hora  time
)
returns void
language plpgsql
security definer
set search_path = 'public'
as $$
begin
  if (p_fecha + p_hora) <= (now() at time zone 'America/Mexico_City') then
    raise exception 'fecha_pasada';
  end if;

  update public.citas
     set fecha = p_fecha,
         hora  = p_hora
   where id = p_id
     and cliente_id = auth.uid()
     and estado in ('pendiente', 'confirmada')
     and (fecha + hora) > (now() at time zone 'America/Mexico_City');

  if not found then
    raise exception 'cita_no_modificable';
  end if;
end;
$$;

-- 8.4 asignar_barbero: elige el barbero disponible y libre de la barberia ---
create or replace function public.asignar_barbero(
  fecha_consulta date,
  hora_consulta  time,
  barberia_id    uuid
)
returns uuid
language sql
stable
security definer
set search_path = 'public'
as $$
  with p as (select fecha_consulta as f, hora_consulta as h, barberia_id as biz)
  select b.id
  from public.barberos b, p
  where b.disponible
    and b.barberia_id = p.biz
    and not exists (
      select 1 from public.citas c
      where c.fecha = p.f
        and c.hora = p.h
        and c.barbero_id = b.id
        and c.barberia_id = p.biz
        and coalesce(c.estado, 'pendiente') <> 'cancelada'
    )
  order by b.created_at asc, b.nombre asc
  limit 1;
$$;

-- 8.5 horas_ocupadas: franjas ya tomadas, para pintar el calendario --------
create or replace function public.horas_ocupadas(
  fecha_consulta date,
  barberia_id     uuid,
  barbero_id      uuid default null
)
returns setof time
language sql
stable
security definer
set search_path = 'public'
as $$

  with p as (select fecha_consulta as f, barberia_id as biz, barbero_id as bid)

  -- 1. Barbero concreto: sus horas ocupadas en esa barberia.
  select c.hora
  from public.citas c, p
  where c.fecha = p.f
    and c.barberia_id = p.biz
    and c.barbero_id = p.bid
    and coalesce(c.estado, 'pendiente') <> 'cancelada'

  union

  -- 2. Esa barberia no tiene ningun barbero disponible: manda cualquier cita
  --    viva del dia.
  select c.hora
  from public.citas c, p
  where c.fecha = p.f
    and c.barberia_id = p.biz
    and coalesce(c.estado, 'pendiente') <> 'cancelada'
    and not exists (
      select 1 from public.barberos b
      where b.disponible and b.barberia_id = p.biz
    )

  union

  -- 3. "Cualquier barbero": horas en las que no queda ni un barbero libre de
  --    esa barberia.
  select h.hora
  from (
    select distinct c2.hora
    from public.citas c2, p
    where c2.fecha = p.f
      and c2.barberia_id = p.biz
      and c2.barbero_id is not null
      and coalesce(c2.estado, 'pendiente') <> 'cancelada'
  ) h, p
  where not exists (
    select 1
    from public.barberos b
    where b.disponible
      and b.barberia_id = p.biz
      and not exists (
        select 1 from public.citas c3, p
        where c3.fecha = p.f
          and c3.hora = h.hora
          and c3.barbero_id = b.id
          and c3.barberia_id = p.biz
          and coalesce(c3.estado, 'pendiente') <> 'cancelada'
      )
  );
$$;

-- 8.6 superadmin_resumen_barberias: metricas de todas las barberias ---------
create or replace function public.superadmin_resumen_barberias()
returns table (
  id uuid, nombre text, slug text, activa boolean, created_at timestamptz,
  citas_mes bigint, citas_total bigint, servicios bigint, barberos bigint,
  productos bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.es_superadmin() then
    raise exception 'solo_superadmin' using errcode = '42501';
  end if;

  return query
    select
      b.id,
      b.nombre,
      b.slug,
      b.activa,
      b.created_at,
      (select count(*) from public.citas c
         where c.barberia_id = b.id
           and c.fecha >= date_trunc('month', timezone('America/Mexico_City', now()))::date
           and c.fecha <  (date_trunc('month', timezone('America/Mexico_City', now())) + interval '1 month')::date),
      (select count(*) from public.citas c where c.barberia_id = b.id),
      (select count(*) from public.servicios s where s.barberia_id = b.id),
      (select count(*) from public.barberos br where br.barberia_id = b.id),
      (select count(*) from public.productos p where p.barberia_id = b.id)
    from public.barberias b
    order by b.created_at desc;
end;
$$;

