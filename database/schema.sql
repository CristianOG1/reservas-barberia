-- 9.4 recordatorios_citas_pendientes: citas de la ventana de aviso ----------
create or replace function public.recordatorios_citas_pendientes(
  p_desde text,
  p_hasta text,
  p_columna_marca text,
  p_maximo integer default 80
)
returns table (
  id uuid, nombre text, correo text, telefono text, servicio text,
  fecha text, hora text, estado text, barbero_nombre text,
  barberia_id uuid, barberia_nombre text
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    c.id,
    c.nombre,
    c.correo,
    c.telefono,
    c.servicio,
    c.fecha::text,
    c.hora::text,
    c.estado,
    b.nombre,
    c.barberia_id,
    br.nombre
  from public.citas c
  left join public.barberos b on b.id = c.barbero_id
  left join public.barberias br on br.id = c.barberia_id
  where coalesce(lower(c.estado), 'pendiente') in ('pendiente', 'confirmada')
    and (c.fecha::text || ' ' || left(c.hora::text, 8)) >= p_desde
    and (c.fecha::text || ' ' || left(c.hora::text, 8)) <= p_hasta
    and (
      case p_columna_marca
        when 'recordatorio_24h_enviado_at' then c.recordatorio_24h_enviado_at
        when 'recordatorio_2h_enviado_at' then c.recordatorio_2h_enviado_at
        else now()
      end
    ) is null
  order by c.fecha, c.hora
  limit greatest(coalesce(p_maximo, 80), 1);
$$;

-- 9.5 reclamar_recordatorios: reserva y marca las citas del canal de correo -
create or replace function public.reclamar_recordatorios(
  p_tipo text,
  p_limite_total integer default 80,
  p_limite_por_barberia integer default 20
)
returns table (
  cita_id uuid, barberia_id uuid, barberia_nombre text, barberia_slug text,
  nombre text, correo text, servicio text, fecha date, hora time,
  barbero_nombre text, zona_horaria text
)
language plpgsql
security definer
set search_path = 'public'
as $$
#variable_conflict use_column
begin
  if p_tipo not in ('24h', '2h') then
    raise exception 'tipo invalido: %', p_tipo;
  end if;

  return query
  with candidatas as (
    select c.id,
           row_number() over (
             partition by c.barberia_id order by c.fecha, c.hora
           ) as rn_barberia
    from public.citas c
    join public.barberias b on b.id = c.barberia_id and b.activa
    join public.configuracion cf on cf.barberia_id = c.barberia_id
                                and cf.recordatorios_activos
    where c.correo is not null
      and btrim(c.correo) <> ''
      and lower(coalesce(c.estado, 'pendiente')) in ('pendiente', 'confirmada')
      and (
        (p_tipo = '24h' and c.recordatorio_24h_enviado_at is null) or
        (p_tipo = '2h'  and c.recordatorio_2h_enviado_at  is null)
      )
      and ((c.fecha + c.hora) at time zone b.zona_horaria)
            >= now() + case when p_tipo = '24h' then interval '23 hours'
                            else interval '1 hour' end
      and ((c.fecha + c.hora) at time zone b.zona_horaria)
            <  now() + case when p_tipo = '24h' then interval '24 hours'
                            else interval '2 hours' end
  ),
  elegidas as (
    select id
    from candidatas
    where rn_barberia <= p_limite_por_barberia
    order by rn_barberia, id
    limit p_limite_total
  ),
  reclamadas as (
    update public.citas c
    set recordatorio_24h_enviado_at =
          case when p_tipo = '24h' then now() else c.recordatorio_24h_enviado_at end,
        recordatorio_2h_enviado_at =
          case when p_tipo = '2h' then now() else c.recordatorio_2h_enviado_at end
    from elegidas e
    where c.id = e.id
    returning c.*
  )
  select r.id, r.barberia_id, b.nombre, b.slug,
         r.nombre, r.correo, r.servicio, r.fecha, r.hora,
         br.nombre, b.zona_horaria
  from reclamadas r
  join public.barberias b on b.id = r.barberia_id
  left join public.barberos br on br.id = r.barbero_id;
end;
$$;

